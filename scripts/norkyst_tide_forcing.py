"""
NorKyst-800 v3's tidal forcing files, read directly (notes/norkyst-issues.md).

    uv run scripts/norkyst_tide_forcing.py <gauges.csv> <fits.csv> [out=output/norkyst_issues/forcing.md]

For the hindcast file (`romshindcast/norkyst_v3/forcing/tide.nc`) and the
operational one (`fou-hi/norkystv3_his_files/static_nc_files/norkyst_tide.nc`):

1. Attributes, constituents and periods.
2. Amplitude ratios of constituent pairs along the four open boundaries
   (wet cells of the first interior row/column): N2/M2, Q1/O1, K2/S2,
   P1/K1, against the gauges' own ratios (year fits, `fits.csv`).
3. The files' values at the gauges (nearest wet cell; the files hold the
   atlas on the whole grid) against the gauges' year fits.
4. The reference date: ROMS forces ζ = A cos(ω (t − TIDE_START) − φ), so
   for the right tide G − φ = V₀(T₀) + u(T₀) with G the Greenwich lag. T₀ is
   searched hourly over 2010–2027 against the gauges' G (circular means
   over the gauges), with and without u; A / H at the gauges is then set
   against f(T₀) (nodal factor applied) and 1 (not applied).

UTide (Codiga 2011) supplies V₀, f and u; `fits.csv` is the output of
`scripts/norkyst_tide_check.sh` (our fit of each gauge's year).
"""

import csv
import sys
from datetime import datetime, timedelta, timezone
from pathlib import Path

import netCDF4
import numpy as np

FILES = {
    "hindcast": "https://thredds.met.no/thredds/dodsC/romshindcast/norkyst_v3/forcing/tide.nc",
    "operational": "https://thredds.met.no/thredds/dodsC/fou-hi/norkystv3_his_files/static_nc_files/norkyst_tide.nc",
}
GRID = "https://thredds.met.no/thredds/dodsC/fou-hi/norkystv3_800m_m00_be"
PAIRS = [("N2", "M2"), ("Q1", "O1"), ("K2", "S2"), ("P1", "K1")]


def wrap(d):
    return (np.asarray(d) + 180.0) % 360.0 - 180.0


def circmean(d):
    z = np.exp(1j * np.radians(d))
    return np.degrees(np.angle(np.nanmean(z, axis=-1)))


def distance(lon1, lat1, lon2, lat2):
    x = np.radians(lon2 - lon1) * np.cos(np.radians(0.5 * (lat1 + lat2)))
    return 6_371_000.0 * np.hypot(x, np.radians(lat2 - lat1))


def table(rows, header):
    out = ["| " + " | ".join(header) + " |", "|" + "|".join("---" for _ in header) + "|"]
    return "\n".join(out + ["| " + " | ".join(str(c) for c in r) + " |" for r in rows])


def astronomy(names, hours_since_2010):
    """V (°) at the given hours since 2010-01-01 and f, u at the same (UTide)."""
    from utide._ut_constants import ut_constants
    from utide.harmonics import FUV

    table_names = list(ut_constants.const.name)
    lind = np.array([table_names.index(n) for n in names])
    day0 = datetime(2010, 1, 1).toordinal()
    t = day0 + hours_since_2010 / 24.0
    # V exactly at every time (no satellites: ngflgs nodsatnone); f and u
    # (slow) daily, interpolated
    _, _, v = FUV(t, t[0], lind, 65.0, [0, 1, 0, 0])
    days = np.arange(np.floor(t[0]), np.ceil(t[-1]) + 1)
    f_d, u_d, _ = FUV(days, days[0], lind, 65.0, [0, 0, 0, 0])
    f = np.stack([np.interp(t, days, f_d[:, k]) for k in range(len(names))], axis=1)
    u = np.stack([np.interp(t, days, u_d[:, k]) for k in range(len(names))], axis=1)
    return (360.0 * v) % 360.0, f, 360.0 * u


def main(argv):
    pos = [a for a in argv if "=" not in a]
    kw = dict(a.split("=", 1) for a in argv if "=" in a)
    if len(pos) != 2:
        print(__doc__)
        sys.exit(1)
    gauges_csv, fits_csv = pos
    out = Path(kw.get("out", "output/norkyst_issues/forcing.md"))
    with open(gauges_csv, newline="", encoding="utf-8") as f:
        gauges = list(csv.DictReader(f))
    year = {}
    with open(fits_csv, newline="", encoding="utf-8") as f:
        for r in csv.DictReader(f):
            code, window = r["label"].split(":")
            if window == "year":
                year.setdefault(code, {})[r["constituent"]] = (float(r["h_ref"]), float(r["g_ref"]))

    grid_cache = Path("data/norkyst_gauges/norkyst_grid.npz")
    if grid_cache.exists():
        g = np.load(grid_cache)
        lon, lat = g["lon"], g["lat"]
    else:
        grid = netCDF4.Dataset(GRID)
        lon, lat = np.asarray(grid["lon"][:]), np.asarray(grid["lat"][:])

    md = ["# NorKyst-800 v3 tidal forcing files", "",
          f"Generated by `scripts/norkyst_tide_forcing.py` on {datetime.now(timezone.utc):%Y-%m-%d}.", ""]
    data = {}
    for label, url in FILES.items():
        ds = netCDF4.Dataset(url)
        attrs = {k: str(getattr(ds, k)) for k in ds.ncattrs()}
        names = attrs.get("constituents", "").split()
        periods = np.asarray(ds["tide_period"][:], dtype=float)
        amp = ds["tide_Eamp"]
        phase = ds["tide_Ephase"]
        ny, nx = amp.shape[1], amp.shape[2]
        md += [f"## {label}: `{url}`", "",
               "Attributes: " + "; ".join(f"{k} = {v}" for k, v in attrs.items()), "",
               "Periods (h): " + ", ".join(f"{n} {p:.6f}" for n, p in zip(names, periods)), ""]
        # Boundaries: the first interior row/column
        sides = {
            "south": (slice(None), 1, slice(None)),
            "north": (slice(None), ny - 2, slice(None)),
            "west": (slice(None), slice(None), 1),
            "east": (slice(None), slice(None), nx - 2),
        }
        idx = {n: k for k, n in enumerate(names)}
        rows, boundary = [], {}
        for side, sl in sides.items():
            a = np.ma.filled(amp[sl], np.nan).astype(float)
            p = np.ma.filled(phase[sl], np.nan).astype(float)
            wet = np.isfinite(a[idx["M2"]]) & (a[idx["M2"]] > 0.01)
            boundary[side] = (a[:, wet], p[:, wet])
            cells = [side, int(wet.sum()), f"{np.median(a[idx['M2'], wet]):.3f}"]
            for x, y in PAIRS:
                cells.append(f"{np.median(a[idx[x], wet] / a[idx[y], wet]):.3f}")
            rows.append(cells)
        gauge_ratio = [np.median([year[c][x][0] / year[c][y][0] for c in year]) for x, y in PAIRS]
        rows.append(["gauges (median of 17 year fits)", "", ""] + [f"{r:.3f}" for r in gauge_ratio])
        md += ["Amplitude ratios along the open boundaries (median over wet cells):", "",
               table(rows, ["side", "cells", "M2 (m)"] + [f"{x}/{y}" for x, y in PAIRS]), ""]

        # At the gauges
        at = {}
        rows = []
        for g in gauges:
            if g["code"] not in year:
                continue
            glat, glon = float(g["lat"]), float(g["lon"])
            d = distance(glon, glat, lon, lat)
            jc, ic = np.unravel_index(np.argmin(d), d.shape)
            j0, i0 = max(jc - 15, 0), max(ic - 15, 0)
            a = np.ma.filled(amp[:, j0:jc + 16, i0:ic + 16], np.nan).astype(float)
            p = np.ma.filled(phase[:, j0:jc + 16, i0:ic + 16], np.nan).astype(float)
            dd = np.where(np.isfinite(a[idx["M2"]]) & (a[idx["M2"]] > 0.01), d[j0:jc + 16, i0:ic + 16], np.inf)
            jw, iw = np.unravel_index(np.argmin(dd), dd.shape)
            at[g["code"]] = (a[:, jw, iw], p[:, jw, iw])
            cells = [g["code"], f"{dd[jw, iw]:.0f}"]
            for n in ["M2", "S2", "N2", "K2", "K1", "O1", "P1", "Q1"]:
                cells.append(f"{a[idx[n], jw, iw] / year[g['code']][n][0]:.2f}")
            rows.append(cells)
        md += ["File amplitude / gauge amplitude (year fit) at the gauges (nearest wet cell, m away):", "",
               table(rows, ["gauge", "m"] + ["M2", "S2", "N2", "K2", "K1", "O1", "P1", "Q1"]), ""]
        data[label] = (names, idx, boundary, at)

        # The reference date
        hours = np.arange(0, 17 * 8766, 1.0)
        V, F, U = astronomy(names, hours)
        codes = sorted(at)
        # G − φ per constituent and gauge
        D = np.array([[year[c][n][1] - at[c][1][idx[n]] for c in codes] for n in names])
        D_mean = circmean(D)
        spread = np.array([np.degrees(np.sqrt(-2 * np.log(abs(np.mean(np.exp(1j * np.radians(D[k])))))))
                           for k in range(len(names))])
        weights = 1.0 / np.maximum(spread, 2.0) ** 2
        results = []
        for with_u in (False, True):
            arg = V + (U if with_u else 0.0)
            resid = wrap(D_mean[None, :] - arg)
            cost = np.sqrt((weights * resid ** 2).sum(axis=1) / weights.sum())
            k = int(np.argmin(cost))
            best = datetime(2010, 1, 1, tzinfo=timezone.utc) + timedelta(hours=float(hours[k]))
            # second best more than 30 days away
            far = np.abs(hours - hours[k]) > 24 * 30
            k2 = int(np.argmin(np.where(far, cost, np.inf)))
            second = datetime(2010, 1, 1, tzinfo=timezone.utc) + timedelta(hours=float(hours[k2]))
            results.append((with_u, best, cost[k], second, cost[k2], resid[k], F[k]))
        md += [f"Reference date T₀ from G − φ at {len(codes)} gauges (circular mean; spread over gauges "
               + ", ".join(f"{n} {s:.0f}°" for n, s in zip(names, spread)) + "):", ""]
        rows = []
        for with_u, best, c, second, c2, resid, f_best in results:
            rows.append(["V₀ + u" if with_u else "V₀ only", f"{best:%Y-%m-%d %H:%M}", f"{c:.1f}",
                         f"{second:%Y-%m-%d %H:%M} ({c2:.1f})",
                         ", ".join(f"{n} {r:+.0f}" for n, r in zip(names, resid))])
        md += [table(rows, ["model", "best T₀ (UTC)", "weighted RMS (°)", "next best > 30 d away",
                            "residual per constituent (°)"]), ""]
        _, best, _, _, _, _, f_best = results[1]
        ratio = {n: np.median([at[c][0][idx[n]] / year[c][n][0] for c in codes]) for n in names}
        f_now = astronomy(names, np.array([(datetime(2025, 1, 1) - datetime(2010, 1, 1)).total_seconds() / 3600.0]))[1][0]
        md += [f"A / H (median over gauges) against f at T₀ = {best:%Y-%m-%d} and at the hindcast/2024–25 "
               "analysis midpoint (2025-01-01):", "",
               table([[n, f"{ratio[n]:.3f}", f"{f_best[k]:.3f}", f"{f_now[k]:.3f}"] for k, n in enumerate(names)],
                     ["constituent", "A_file / H_gauge", "f(T₀)", "f(2025-01-01)"]), ""]

    # Old against new
    (names, idx, bh, _), (_, _, bo, _) = data["hindcast"], data["operational"]
    rows = []
    for n in names:
        ra = np.concatenate([bo[s][0][idx[n]] / bh[s][0][idx[n]] for s in bh])
        dp = np.concatenate([wrap(bo[s][1][idx[n]] - bh[s][1][idx[n]]) for s in bh])
        rows.append([n, f"{np.median(ra):.3f}", f"{np.median(dp):+.1f}", f"{np.percentile(dp, 5):+.1f}…{np.percentile(dp, 95):+.1f}"])
    md += ["## Operational against hindcast, along the boundaries", "",
           table(rows, ["constituent", "amplitude ratio (median)", "Δφ median (°)", "Δφ 5–95 %"]), ""]
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(md), encoding="utf-8")
    sys.stdout.reconfigure(encoding="utf-8")
    print("\n".join(md))


if __name__ == "__main__":
    main(sys.argv[1:])
